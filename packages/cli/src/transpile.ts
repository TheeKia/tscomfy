import { basename, dirname, isAbsolute, join, relative, sep } from "node:path";
import { CODEGEN_VERSION, isExportName, transpile } from "@tscomfy/codegen";
import {
  defineSchema,
  hashSchema,
  importApi,
  importUi,
  type JsonValue,
  parse,
  stringify,
} from "@tscomfy/core";
import { type Flags, parseFlags, value } from "./args.ts";
import { loadSchema, path, SNAPSHOT } from "./generate.ts";
import { CliError, type Io } from "./io.ts";
import { MANIFEST, readManifest } from "./manifest.ts";
import { count, formatDiagnostic } from "./report.ts";
import { isRecord, shellQuote } from "./util.ts";

/** `tscomfy transpile --help`. */
export const TRANSPILE_USAGE: string = `Usage: tscomfy transpile (--prompt <prompt.json> | --workflow <workflow.json>) --schema <dir> [options]

Turns an API-format prompt (the frontend's "Export (API)"), or a UI workflow (its "Save" or
"Export"), into TypeScript that builds it with the types \`tscomfy generate\` wrote into <dir>.
Running the code and exporting gives the prompt back: for a UI workflow, the prompt the frontend
would queue for it, with Reroutes, PrimitiveNodes and subgraphs resolved. Nodes the types can't
express are written as raw(…), with a warning.

Options:
  --prompt <file>      The prompt to transpile.
  --workflow <file>    The UI workflow to transpile, instead of a prompt.
  --schema <dir>       The directory \`tscomfy generate\` wrote (it reads ${SNAPSHOT} and ${MANIFEST}).
  --out <file>         Where to write the module. Default: standard output, importing the
                       schema relative to the current directory.
  --name <identifier>  The exported constant. Default: from the prompt's file name.
  --no-inline          Give every node a variable, rather than inlining those used once.
`;

const FLAGS = [
  { name: "prompt", takesValue: true },
  { name: "workflow", takesValue: true },
  { name: "schema", takesValue: true },
  { name: "out", takesValue: true },
  { name: "name", takesValue: true },
  { name: "no-inline", takesValue: false },
  { name: "help", takesValue: false },
] as const;

/** `tscomfy transpile`. */
export async function transpileCommand(io: Io, args: readonly string[]): Promise<number> {
  const flags = parseFlags(args, FLAGS);
  if (flags.has("help")) {
    io.out(TRANSPILE_USAGE);
    return 0;
  }
  if (flags.has("prompt") && flags.has("workflow")) {
    throw new CliError("Pass --prompt or --workflow, not both.", 2);
  }
  if (!flags.has("prompt") && !flags.has("workflow")) {
    throw new CliError("--prompt or --workflow is required.", 2);
  }
  const kind = flags.has("workflow") ? "workflow" : "prompt";
  const promptPath = path(flags, kind);
  const schemaDir = path(flags, "schema");
  const out = flags.has("out") ? path(flags, "out") : undefined;
  const manifest = await readManifest(io, schemaDir);
  const snapshotPath = join(schemaDir, SNAPSHOT);
  const snapshot = await io.readText(snapshotPath);
  if (manifest === undefined || snapshot === undefined) {
    throw new CliError(
      `There is no ${manifest === undefined ? MANIFEST : SNAPSHOT} in ${schemaDir}; run tscomfy generate first.`,
    );
  }
  const name = readName(flags, promptPath, manifest.exportName);
  const text = await io.readText(promptPath);
  if (text === undefined) throw new CliError(`There is no file at ${promptPath}.`);

  const schema = loadSchema({ text: snapshot, label: snapshotPath, flag: "" }).schema;
  // The types in <dir> must be the ones this version would write, or the code won't fit them.
  if (manifest.codegen !== CODEGEN_VERSION || manifest.schema !== hashSchema(schema)) {
    throw new CliError(
      `${schemaDir} was generated by another version of tscomfy; run tscomfy generate again first.`,
    );
  }
  const what = kind === "prompt" ? "a prompt" : "a UI workflow";
  const mixUp = kind === "prompt" ? notAPrompt(text) : notAWorkflow(text);
  if (mixUp !== undefined) throw new CliError(`${promptPath} isn't ${what}: ${mixUp}`);
  const typed = defineSchema(stringify(schema));
  const imported = kind === "prompt" ? importApi(text, typed) : importUi(text, typed);
  const fatal = imported.diagnostics.find(
    (diagnostic) =>
      diagnostic.path.length === 0 &&
      (diagnostic.code === "E_INVALID_JSON" ||
        diagnostic.code === "E_INVALID_PROMPT" ||
        diagnostic.code === "E_INVALID_WORKFLOW"),
  );
  if (fatal !== undefined) {
    throw new CliError(`${promptPath} isn't ${what}: ${fatal.message}`);
  }
  if (imported.workflow.graph.nodes.size === 0) {
    throw new CliError(`${promptPath} isn't ${what}: it has no node that can be read.`);
  }
  const command = [
    "tscomfy transpile",
    `--${kind} ${shellQuote(promptPath)}`,
    `--schema ${shellQuote(schemaDir)}`,
    ...(out === undefined ? [] : [`--out ${shellQuote(out)}`]),
    ...(flags.has("name") ? [`--name ${name}`] : []),
    ...(flags.has("no-inline") ? ["--no-inline"] : []),
  ].join(" ");
  const result = transpile(imported.workflow, {
    name,
    schemaModule: moduleSpecifier(out, schemaDir, manifest.importExtension),
    schemaName: manifest.exportName,
    inline: !flags.has("no-inline"),
    header: [`Regenerate with: ${command}`],
  });

  for (const diagnostic of [...imported.diagnostics, ...result.diagnostics]) {
    io.err(`${formatDiagnostic(diagnostic)}\n`);
  }
  if (out === undefined) {
    io.out(result.code);
    return 0;
  }
  await io.writeText(out, result.code);
  io.out(
    `Transpiled ${count(imported.workflow.graph.nodes.size, "node")} from ${promptPath} into ${out}.\n`,
  );
  return 0;
}

/**
 * What a file that isn't a prompt looks like instead, when it is a common mix-up: the frontend's
 * UI workflow (`nodes` and `links`), or a `POST /prompt` body (`{ "prompt": … }`).
 */
function notAPrompt(text: string): string | undefined {
  const parsed = parse(text).value;
  if (parsed === undefined || !isRecord(parsed)) return undefined;
  if (isUiWorkflow(parsed)) return "it is a UI workflow; pass it with --workflow instead.";
  // A node with the id "prompt" has a class_type; a POST /prompt body's prompt doesn't.
  const prompt = parsed["prompt"];
  if (prompt !== undefined && isRecord(prompt) && !Object.hasOwn(prompt, "class_type")) {
    return "it is a POST /prompt body; save its prompt on its own.";
  }
  return undefined;
}

/** What a file passed as a UI workflow looks like instead: a prompt, or a `POST /prompt` body. */
function notAWorkflow(text: string): string | undefined {
  const parsed = parse(text).value;
  if (parsed === undefined || !isRecord(parsed) || isUiWorkflow(parsed)) return undefined;
  const nodes = Object.values(parsed);
  if (nodes.length > 0 && nodes.every((node) => isRecord(node) && "class_type" in node)) {
    return "it is an API prompt; pass it with --prompt instead.";
  }
  if (Object.hasOwn(parsed, "prompt")) {
    return "it is a POST /prompt body; save its prompt on its own and pass it with --prompt.";
  }
  return undefined;
}

function isUiWorkflow(parsed: { readonly [key: string]: JsonValue }): boolean {
  return Array.isArray(parsed["nodes"]) && Array.isArray(parsed["links"]);
}

/**
 * How the module imports the schema: relative to where it is written (the current directory
 * without --out), with POSIX separators.
 */
function moduleSpecifier(out: string | undefined, schemaDir: string, extension: string): string {
  const from = out === undefined ? "." : dirname(out);
  const target = relative(from, join(schemaDir, `index${extension}`));
  // On another drive (Windows) there is no relative path.
  if (isAbsolute(target)) {
    throw new CliError(
      "--schema and --out are on different drives; no relative import joins them.",
    );
  }
  const posix = target.split(sep).join("/");
  return posix.startsWith("./") || posix.startsWith("../") ? posix : `./${posix}`;
}

/** The export name: `--name`, or from the prompt's file name (`Anima-API.json` → `animaApi`). */
function readName(flags: Flags, promptPath: string, schemaName: string): string {
  const given = value(flags, "name");
  const name = given ?? camel(basename(promptPath).replace(/\.[^.]*$/, ""));
  if (BUILDER_NAMES.includes(schemaName)) {
    throw new CliError(
      `The schema's export name, ${schemaName}, is one the transpiled module needs itself; run tscomfy generate again with another --name.`,
    );
  }
  const taken = name === schemaName || BUILDER_NAMES.includes(name);
  // The declaration must fit on one line: `export const <name>: Workflow<NodesOf<…>> =`. Export
  // names are ASCII, so their length is their width.
  const long = `export const ${name}: Workflow<NodesOf<typeof ${schemaName}>> =`.length > 100;
  if (!isExportName(name) || taken || long) {
    const why = taken
      ? `the module itself uses it (${[schemaName, ...BUILDER_NAMES].join(", ")})`
      : long
        ? "it is too long for the declaration's line"
        : "it must be an identifier, not a reserved word";
    throw new CliError(
      given === undefined
        ? `Can't name the export ${JSON.stringify(name)}, after ${JSON.stringify(promptPath)}: ${why}; pass --name.`
        : `--name ${JSON.stringify(given)} isn't usable: ${why}.`,
      2,
    );
  }
  return name;
}

/** Names the transpiled module imports or binds itself. */
const BUILDER_NAMES: readonly string[] = ["workflow", "Workflow", "NodesOf", "n", "raw"];

/** camelCase from the runs of letters and digits: `Anima-API` → `animaApi`. */
function camel(text: string): string {
  const words = text.match(/[A-Za-z0-9]+/g) ?? [];
  return words
    .map((word, index) => {
      const lower = word === word.toUpperCase() ? word.toLowerCase() : word;
      return index === 0
        ? lower.charAt(0).toLowerCase() + lower.slice(1)
        : lower.charAt(0).toUpperCase() + lower.slice(1);
    })
    .join("");
}
