import { join } from "node:path";
import { CODEGEN_VERSION } from "@tscomfy/codegen";
import {
  diffSchemas,
  hashSchema,
  type InputChange,
  type NodeChange,
  type Schema,
  type SchemaDiff,
} from "@tscomfy/core";
import { HELP, parseFlags, required } from "./args.ts";
import { regenerateCommand } from "./generate.ts";
import type { Io } from "./io.ts";
import { contentHash, FILES, MANIFEST, readGenerated, SNAPSHOT } from "./manifest.ts";
import { count } from "./report.ts";
import { loadSchema, readSource } from "./source.ts";
import { printable } from "./util.ts";

/** `tscomfy check --help`. */
export const CHECK_USAGE: string = `Usage: tscomfy check (--url <server> | --from <object_info.json>) --out <dir>

Compares the server's node definitions with the snapshot in <dir>/${SNAPSHOT}, and checks
that the files in <dir> are exactly what \`tscomfy generate\` wrote (<dir>/${MANIFEST}). Exits
with 1 when anything differs, so it can guard a build. New files in upload and remote combos
(an uploaded image) are runtime state, not drift.

Options:
  --url <server>   A ComfyUI server, e.g. http://127.0.0.1:8188. Only GET requests.
  --from <file>    A saved /object_info response instead of a server.
  --out <dir>      The directory \`tscomfy generate\` wrote.
  --verbose        List every changed node, input and combo option, rather than the first few.
  -h, --help       Show this help.
`;

const FLAGS = [
  { name: "url", takesValue: true },
  { name: "from", takesValue: true },
  { name: "out", takesValue: true },
  { name: "verbose", takesValue: false },
  HELP,
] as const;

/** How many node and input names a list shows before the rest are counted, unless verbose. */
const SHOWN_NAMES = 10;

/** How many combo options a change lists before the rest are counted, unless verbose. */
const SHOWN_OPTIONS = 5;

/** What follows a count of entries left out. */
const MORE = " (--verbose shows all)";

/** `tscomfy check`. */
export async function checkCommand(io: Io, args: readonly string[]): Promise<number> {
  const flags = parseFlags(args, FLAGS);
  if (flags.has("help")) {
    io.out(CHECK_USAGE);
    return 0;
  }
  const out = required(flags, "out");
  const verbose = flags.has("verbose");
  const { manifest, snapshotPath, snapshotText, schema: snapshot } = await readGenerated(io, out);
  const source = await readSource(io, flags);
  const current = loadSchema(source).schema;

  // Files that don't hash as recorded were edited, removed or left half-written.
  const stale: string[] = [];
  for (const file of FILES) {
    const hash = manifest.files[file];
    // Sequential: a few small reads, and a stable order for the message.
    // oxlint-disable-next-line no-await-in-loop
    const text = file === SNAPSHOT ? snapshotText : await io.readText(join(out, file));
    if (text === undefined || contentHash(text) !== hash) stale.push(file);
  }
  // Another codegen, or another core normalizing the same snapshot differently.
  const outdated = manifest.codegen !== CODEGEN_VERSION || manifest.schema !== hashSchema(snapshot);
  const { diff, runtime } = withoutRuntimeOptions(diffSchemas(snapshot, current), current);
  const drifted = diff.added.length + diff.removed.length + diff.changed.length > 0;

  const ignored =
    runtime.length === 0
      ? ""
      : ` (changed files in ${count(runtime.length, "upload or remote combo")} aren't drift: ${printable(listed(runtime, verbose, SHOWN_NAMES))})`;
  if (!drifted && stale.length === 0 && !outdated) {
    const nodes = Object.keys(current.nodes).length;
    io.out(
      `Up to date: ${count(nodes, "node type")} ${nodes === 1 ? "matches" : "match"} ${snapshotPath}${ignored}.\n`,
    );
    return 0;
  }
  const lines: string[] = [];
  if (stale.length > 0) {
    lines.push(
      `${list(stale)} in ${out} ${stale.length === 1 ? "isn't" : "aren't"} what tscomfy generate wrote: edited, missing, or from an interrupted run.`,
    );
  }
  if (outdated) {
    lines.push(
      manifest.codegen === CODEGEN_VERSION
        ? `${out} was generated by another version of tscomfy, which read the snapshot differently.`
        : `${out} was generated by @tscomfy/codegen ${manifest.codegen}; this is ${CODEGEN_VERSION}.`,
    );
  }
  if (drifted) {
    lines.push(
      `${source.label} differs from ${snapshotPath}${ignored}:`,
      ...formatDiff(diff, verbose).map(printable),
    );
  }
  const command = regenerateCommand({
    flag: source.flag,
    out,
    exportName: manifest.exportName,
    importExtension: manifest.importExtension,
    // With --url, the server says again. With --from, the recorded version is the snapshot's,
    // so it goes with that file only, as generate reads it.
    ...(flags.has("from") &&
    manifest.comfyVersion !== undefined &&
    contentHash(source.text) === manifest.files[SNAPSHOT]
      ? { comfyVersion: manifest.comfyVersion }
      : {}),
  });
  lines.push(`Run ${command} to update.`);
  io.out(`${lines.join("\n")}\n`);
  return 1;
}

/**
 * The diff without option changes of upload and remote combos (docs/plan.md §6.5): their options
 * are the server's files, which change with every upload, and the types take any string there.
 * Also returns those inputs, as `Class.input`.
 */
function withoutRuntimeOptions(
  diff: SchemaDiff,
  current: Schema,
): { readonly diff: SchemaDiff; readonly runtime: readonly string[] } {
  const runtime: string[] = [];
  const changed: NodeChange[] = [];
  for (const change of diff.changed) {
    const inputs = current.nodes[change.classType]?.inputs ?? [];
    const kept = change.inputsChanged.filter((input: InputChange) => {
      const definition = inputs.find((each) => each.name === input.name);
      const runtimeOnly =
        !input.specChanged &&
        definition?.kind === "combo" &&
        (definition.upload || definition.remote);
      if (runtimeOnly) runtime.push(`${change.classType}.${input.name}`);
      return !runtimeOnly;
    });
    const rest = { ...change, inputsChanged: kept };
    const empty =
      kept.length === 0 &&
      rest.inputsAdded.length === 0 &&
      rest.inputsRemoved.length === 0 &&
      !rest.outputsChanged &&
      !rest.detailsChanged;
    if (!empty) changed.push(rest);
  }
  return { diff: { ...diff, changed }, runtime };
}

/**
 * The diff as indented lines: every list (nodes, inputs, options, changed nodes) cut to its
 * first few entries unless `verbose`, so a server that differs a lot still gives short lines.
 */
function formatDiff(diff: SchemaDiff, verbose: boolean): string[] {
  const lines: string[] = [];
  if (diff.added.length > 0) {
    lines.push(
      `  + ${count(diff.added.length, "node")} added: ${listed(diff.added, verbose, SHOWN_NAMES)}`,
    );
  }
  if (diff.removed.length > 0) {
    lines.push(
      `  - ${count(diff.removed.length, "node")} removed: ${listed(diff.removed, verbose, SHOWN_NAMES)}`,
    );
  }
  if (diff.changed.length > 0) {
    lines.push(`  ~ ${count(diff.changed.length, "node")} changed:`);
    const shown = verbose ? diff.changed : diff.changed.slice(0, SHOWN_NAMES);
    for (const change of shown) lines.push(...formatChange(change, verbose));
    if (shown.length < diff.changed.length) {
      lines.push(`    … and ${String(diff.changed.length - shown.length)} more${MORE}`);
    }
  }
  return lines;
}

function formatChange(change: NodeChange, verbose: boolean): string[] {
  const lines = [`    ${change.classType}`];
  if (change.inputsAdded.length > 0) {
    lines.push(`      inputs added: ${listed(change.inputsAdded, verbose, SHOWN_NAMES)}`);
  }
  if (change.inputsRemoved.length > 0) {
    lines.push(`      inputs removed: ${listed(change.inputsRemoved, verbose, SHOWN_NAMES)}`);
  }
  for (const input of change.inputsChanged) {
    const options = (values: readonly (string | number | boolean)[]): string =>
      listed(
        values.map((option) => JSON.stringify(option)),
        verbose,
        SHOWN_OPTIONS,
      );
    const parts = [
      ...(input.optionsAdded.length > 0 ? [`+ ${options(input.optionsAdded)}`] : []),
      ...(input.optionsRemoved.length > 0 ? [`- ${options(input.optionsRemoved)}`] : []),
      ...(input.specChanged ? ["spec changed"] : []),
    ];
    lines.push(`      ${input.name}: ${parts.join("; ")}`);
  }
  if (change.outputsChanged) lines.push("      outputs changed");
  if (change.detailsChanged)
    lines.push("      details changed (name, category, description, flags or order)");
  return lines;
}

/** `a, b, c`, or the first `limit` and `… and 4 more (--verbose shows all)` unless `verbose`. */
function listed(items: readonly string[], verbose: boolean, limit: number): string {
  const shown = verbose ? items : items.slice(0, limit);
  const rest = items.length - shown.length;
  return rest > 0 ? `${shown.join(", ")}, … and ${String(rest)} more${MORE}` : shown.join(", ");
}

/** `a`, `a and b`, `a, b and c`. */
function list(items: readonly string[]): string {
  return items.length <= 1
    ? items.join("")
    : `${items.slice(0, -1).join(", ")} and ${items.at(-1) ?? ""}`;
}
