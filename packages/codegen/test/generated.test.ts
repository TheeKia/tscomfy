import { describe, expect, test } from "bun:test";
import { join } from "node:path";
import { CODEGEN_VERSION, emitSchemaModule, generate } from "@tscomfy/codegen";
import { normalizeObjectInfo } from "@tscomfy/core";
import { MOCK_OBJECT_INFO_NAMES, readMockObjectInfo } from "@tscomfy/fixtures";
import {
  ACCEPTS_MATRIX_PATH,
  acceptsMatrix,
  GENERATED_DIR,
  generateMock,
} from "./generated-fixtures.ts";

describe("committed fixtures", () => {
  test.each(MOCK_OBJECT_INFO_NAMES)(
    "%s is up to date (bun run generate:fixtures)",
    async (name) => {
      const { files } = await generateMock(name);
      const committed = await Promise.all(
        files.map((file) => Bun.file(join(GENERATED_DIR, name, file.path)).text()),
      );
      expect(committed).toEqual(files.map((file) => file.contents));
    },
  );

  test.each(MOCK_OBJECT_INFO_NAMES)(
    "%s/index.ts loads the schema it was generated from",
    async (name) => {
      const module: unknown = await import(join(GENERATED_DIR, name, "index.ts"));
      const { schema } = normalizeObjectInfo(await readMockObjectInfo(name), {
        comfyVersion: "0.41.0",
      });
      if (typeof module !== "object" || module === null || !("mock" in module)) {
        throw new Error("expected the module to export mock");
      }
      expect(module.mock).toEqual(schema);
    },
  );
});

describe("accepts matrix", () => {
  test("is up to date (bun run generate:fixtures)", async () => {
    expect(await Bun.file(ACCEPTS_MATRIX_PATH).text()).toBe(await acceptsMatrix());
  });
});

describe("generate", () => {
  test("is deterministic", async () => {
    const { schema } = normalizeObjectInfo(await readMockObjectInfo("dynamic-combo"));
    const first = generate(schema, { exportName: "local" });
    expect(generate(schema, { exportName: "local" })).toEqual(first);
  });

  test("records the schema hash, ComfyUI version and command in both headers", async () => {
    const { schema } = normalizeObjectInfo(await readMockObjectInfo("basic-pipeline"), {
      comfyVersion: "0.41.0",
    });
    const { files } = generate(schema, {
      exportName: "local",
      command: "tscomfy generate --url x",
    });
    for (const file of files) {
      expect(file.contents).toStartWith(
        `// Generated by @tscomfy/codegen ${CODEGEN_VERSION}. Do not edit: regenerate instead.\n// Schema sha256:`,
      );
      expect(file.contents).toContain(
        ", ComfyUI 0.41.0.\n// Regenerate with: tscomfy generate --url x\n",
      );
    }
  });

  test("imports nodes.ts with the configured extension", async () => {
    const { schema } = normalizeObjectInfo(await readMockObjectInfo("basic-pipeline"));
    const index = (extension?: ".js" | ".ts"): string | undefined =>
      generate(schema, {
        exportName: "local",
        ...(extension === undefined ? {} : { importExtension: extension }),
      }).files.find((file) => file.path === "index.ts")?.contents;
    expect(index()).toContain('import type { Nodes } from "./nodes.js";');
    expect(index(".ts")).toContain('import type { Nodes } from "./nodes.ts";');
  });

  test("CODEGEN_VERSION matches package.json", async () => {
    const manifest: unknown = await Bun.file(join(import.meta.dir, "../package.json")).json();
    expect(manifest).toMatchObject({ version: CODEGEN_VERSION });
  });

  test("rejects an export name that isn't an identifier", async () => {
    const { schema } = normalizeObjectInfo(await readMockObjectInfo("basic-pipeline"));
    expect(() => emitSchemaModule(schema, "my-schema", "./nodes.js")).toThrow(TypeError);
  });
});

describe("diagnostics", () => {
  test("W_EMPTY_COMBO for combos without options, but not remote ones", async () => {
    const { diagnostics } = await generateMock("combos");
    expect(diagnostics.map((diagnostic) => [diagnostic.code, diagnostic.path])).toEqual([
      ["W_EMPTY_COMBO", ["MockComboEmpty", "legacy_empty"]],
      ["W_EMPTY_COMBO", ["MockComboEmpty", "v2_empty"]],
    ]);
    expect(diagnostics[0]?.severity).toBe("warning");
  });

  test("W_UNTYPED_INPUT for inputs the normalizer couldn't read", async () => {
    const { diagnostics } = await generateMock("malformed");
    expect(diagnostics.map((diagnostic) => diagnostic.code)).toContain("W_UNTYPED_INPUT");
    expect(diagnostics.map((diagnostic) => diagnostic.path)).toContainEqual([
      "MockBadInputSpecs",
      "null_spec",
    ]);
  });
});
