// Writes src/text-width-tables.ts: the character classes `textWidth` needs, measured from oxfmt
// itself (see width-probe.ts), so generated code breaks lines where oxfmt does. Run it after
// updating oxfmt; text-width.test.ts fails until the tables match the oxfmt installed.

import { join } from "node:path";
import { oxfmt, REPO_DIR } from "@tscomfy/fixtures";
import { oxfmtWidths, probedCodePoints } from "./width-probe.ts";

const TABLES_PATH = join(REPO_DIR, "packages", "codegen", "src", "text-width-tables.ts");

/** What the variation selectors, a ZWJ, a skin tone and the Arabic letters mean here. */
const VS15 = "\u{FE0E}";
const VS16 = "\u{FE0F}";
const ZWJ = "\u{200D}";
const EMOJI = "\u{1F600}";
const SKIN_TONE = "\u{1F3FD}";
const LAM = "\u{644}";
const ALEF = "\u{627}";

const codes = probedCodePoints();
const widths = await oxfmtWidths(
  codes.map((code) => String.fromCodePoint(code)),
  2,
);
const widthOf = new Map(codes.map((code, index) => [code, widths[index] ?? 1]));
const ofWidth = (width: number): number[] => codes.filter((code) => widthOf.get(code) === width);
const wide = ofWidth(2);
const zero = ofWidth(0);
// Printable ASCII but `"` and `\`, which the probes can't hold: keycap bases are among them.
const ascii = Array.from({ length: 0x5f }, (_, index) => index + 0x20).filter(
  (code) => code !== 0x22 && code !== 0x5c,
);
const narrow = [...ascii, ...ofWidth(1)];

/** The codes for which `sequence(code)` measures `width`. */
async function where(
  candidates: readonly number[],
  sequence: (char: string) => string,
  most: number,
  width: number,
): Promise<number[]> {
  const measured = await oxfmtWidths(
    candidates.map((code) => sequence(String.fromCodePoint(code))),
    most,
  );
  return candidates.filter((_, index) => measured[index] === width);
}

// Wide emoji: after an emoji and a ZWJ, they add nothing.
const emoji = await where(
  wide.filter((code) => code < 0x20000),
  (char) => `${EMOJI}${ZWJ}${char}`,
  4,
  2,
);
// Emoji presentation sequences: VS16 widens a narrow base; a wide base with VS16 vanishes when a
// ZWJ joins it to the emoji after it, where a wide emoji without such a sequence doesn't.
const emojiBases = [
  ...(await where(narrow, (char) => `${char}${VS16}`, 2, 2)),
  ...(await where(wide, (char) => `${char}${VS16}${ZWJ}${EMOJI}`, 4, 2)),
];
// Text presentation sequences: VS15 narrows a wide base.
const textBases = await where(wide, (char) => `${char}${VS15}`, 2, 1);
// Skin tone bases: the base and its tone take two columns together.
const modifierBases = await where(
  [...new Set([...emoji, ...emojiBases])].toSorted((a, b) => a - b),
  (char) => `${char}${SKIN_TONE}`,
  4,
  2,
);
// The Lam-Alef ligature: a lam and an alef, with marks between them, take one column.
const arabic = narrow.filter((code) => code >= 0x600 && code < 0x900);
const alefs = await where(arabic, (char) => `${LAM}${char}`, 2, 1);
const lams = await where(arabic, (char) => `${char}${ALEF}`, 2, 1);
const transparent = await where(zero, (char) => `${LAM}${char}${ALEF}`, 2, 1);

const tables: [string, string, readonly number[]][] = [
  ["ZERO_WIDTH", "Characters that take no column.", zero],
  ["WIDE", "Characters that take two columns.", wide],
  ["EMOJI", "Wide emoji, which a ZWJ joins into the emoji before it.", emoji],
  ["EMOJI_BASES", "Bases of emoji presentation sequences: VS16 makes them wide emoji.", emojiBases],
  ["TEXT_BASES", "Bases of text presentation sequences: VS15 makes them narrow.", textBases],
  ["MODIFIER_BASES", "Emoji a skin tone joins.", modifierBases],
  ["ALEFS", "Letters of the Arabic alef joining group, which form a ligature with a lam.", alefs],
  ["LAMS", "Arabic lams.", lams],
  ["TRANSPARENT", "Marks that may stand between a lam and an alef.", transparent],
];
const manifest: unknown = await Bun.file(
  join(REPO_DIR, "node_modules", "oxfmt", "package.json"),
).json();
const version: unknown =
  typeof manifest === "object" && manifest !== null ? Reflect.get(manifest, "version") : undefined;
if (typeof version !== "string") throw new Error("oxfmt's package.json has no version");
const source = [
  `// Generated by test/update-widths.ts from oxfmt ${version}: do not edit. Each table is a`,
  "// sorted list of inclusive code point ranges, start and end in turn.",
  "",
  ...tables.flatMap(([name, doc, members]) => [
    `/** ${doc} */`,
    `export const ${name}: readonly number[] = [${ranges(members).join(", ")}];`,
    "",
  ]),
].join("\n");
const formatted = await oxfmt(TABLES_PATH, source);
if (formatted.code !== 0) throw new Error(formatted.stderr);
await Bun.write(TABLES_PATH, formatted.stdout);
console.log(`Wrote ${TABLES_PATH}`);

/** Sorted code points as ranges, written as hex literals: start, end, start, end, \u{2026} */
function ranges(members: readonly number[]): string[] {
  const sorted = [...new Set(members)].toSorted((a, b) => a - b);
  const bounds: number[] = [];
  for (const code of sorted) {
    if (bounds.length > 0 && bounds.at(-1) === code - 1) bounds[bounds.length - 1] = code;
    else bounds.push(code, code);
  }
  return bounds.map((code) => `0x${code.toString(16)}`);
}
