// The generated output for every mock, committed under test/generated/ so tsc type-checks it,
// oxfmt checks its formatting, and the type tests (*.test-d.ts) can import it. Regenerate with
// `bun run generate:fixtures`; generated.test.ts fails while the committed copy is stale.

import { join } from "node:path";
import { generate, type GenerateResult, transpile, type TranspileResult } from "@tscomfy/codegen";
import { accepts, defineSchema, importApi, normalizeObjectInfo, stringify } from "@tscomfy/core";
import {
  type MockApiWorkflowName,
  type MockObjectInfoName,
  readMockApiWorkflow,
  readMockObjectInfo,
} from "@tscomfy/fixtures";

/** Where the committed fixtures live. */
export const GENERATED_DIR: string = join(import.meta.dir, "generated");

/** Generates one mock's files exactly as committed. */
export async function generateMock(name: MockObjectInfoName): Promise<GenerateResult> {
  const { schema } = normalizeObjectInfo(await readMockObjectInfo(name), {
    comfyVersion: "0.41.0",
  });
  return generate(schema, {
    exportName: "mock",
    command: "bun run generate:fixtures",
  });
}

/** Where the backend's link matrix for the accepts mock lives. */
export const ACCEPTS_MATRIX_PATH: string = join(GENERATED_DIR, "accepts-matrix.ts");

/**
 * `accepts()` on every input × output pair of the accepts mock, as a type: the backend's side of
 * the accepts table (docs/plan.md §5.2). accepts-table.test-d.ts checks the generated types
 * against it pair by pair.
 */
export async function acceptsMatrix(): Promise<string> {
  const { schema } = normalizeObjectInfo(await readMockObjectInfo("accepts"));
  const inputs = schema.nodes["MockAcceptsInputs"]?.inputs ?? [];
  const outputs = schema.nodes["MockAcceptsOutputs"]?.outputs ?? [];
  const lines = [
    "// accepts() on every input × output pair of the accepts mock. Generated by",
    "// `bun run generate:fixtures`; do not edit.",
    "",
    "/** Whether the backend accepts a link from each output (inner key) into each input. */",
    "export interface Backend {",
  ];
  for (const input of inputs) {
    lines.push(`  readonly ${input.name}: {`);
    for (const output of outputs) {
      lines.push(`    readonly ${output.name}: ${String(accepts(input, output))};`);
    }
    lines.push("  };");
  }
  lines.push("}", "");
  return lines.join("\n");
}

/** The mock schema each mock prompt was written for. */
export const PROMPT_SCHEMAS: Record<MockApiWorkflowName, MockObjectInfoName> = {
  autogrow: "autogrow",
  "dynamic-combo": "dynamic-combo",
  "dynamic-group": "dynamic-group",
  lists: "combos",
  txt2img: "basic-pipeline",
  "value-widgets": "widget-types",
};

/** Where the transpiled mock prompts live, one module each, over the generated fixtures. */
export const TRANSPILED_DIR: string = join(GENERATED_DIR, "transpiled");

/** A mock prompt transpiled exactly as committed: `export const prompt`, over `mock`. */
export async function transpileMock(name: MockApiWorkflowName): Promise<TranspileResult> {
  const schemaName = PROMPT_SCHEMAS[name];
  const { schema } = normalizeObjectInfo(await readMockObjectInfo(schemaName));
  const { workflow } = importApi(await readMockApiWorkflow(name), defineSchema(stringify(schema)));
  return transpile(workflow, {
    name: "prompt",
    schemaModule: `../${schemaName}/index.ts`,
    schemaName: "mock",
    header: ["Regenerate with: bun run generate:fixtures"],
  });
}
