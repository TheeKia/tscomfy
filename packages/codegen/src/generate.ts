import { type Diagnostic, hashSchema, type Schema } from "@tscomfy/core";
import { emitSchemaModule } from "./emit-schema-module.ts";
import { emitTypes } from "./emit-types.ts";

/** The version written into generated headers. A test keeps it equal to package.json. */
export const CODEGEN_VERSION = "0.1.1";

/** A file to write, as data: codegen never touches the filesystem. */
export interface GeneratedFile {
  /** Relative to the output directory. */
  readonly path: string;
  readonly contents: string;
}

/** Options for {@link generate}. */
export interface GenerateOptions {
  /** The exported schema constant, e.g. `local`: one `exportNameProblem` finds nothing wrong with. */
  readonly exportName: string;
  /**
   * The extension `index.ts` uses to import `nodes.ts`: `.js` (the default) works under
   * `nodenext` and `bundler` resolution; `.ts` needs `allowImportingTsExtensions` or
   * `rewriteRelativeImportExtensions`.
   */
  readonly importExtension?: ".js" | ".ts";
  /** The command that regenerates the files, recorded in their headers. */
  readonly command?: string;
}

/** The result of {@link generate}. */
export interface GenerateResult {
  /** `nodes.ts` and `index.ts`. */
  readonly files: readonly GeneratedFile[];
  readonly diagnostics: readonly Diagnostic[];
}

/**
 * Generates the files for one schema: `nodes.ts` (types only) and `index.ts` (the typed runtime
 * schema). Pure and deterministic. Throws a `TypeError` for an export name `exportNameProblem`
 * refuses.
 */
export function generate(schema: Schema, options: GenerateOptions): GenerateResult {
  const header = [
    `Generated by @tscomfy/codegen ${CODEGEN_VERSION}. Do not edit: regenerate instead.`,
    `Schema ${hashSchema(schema)}${schema.comfyVersion === undefined ? "" : `, ComfyUI ${schema.comfyVersion}`}.`,
    ...(options.command === undefined ? [] : [`Regenerate with: ${options.command}`]),
  ];
  const types = emitTypes(schema, header);
  const nodesModule = `./nodes${options.importExtension ?? ".js"}`;
  return {
    files: [
      { path: "nodes.ts", contents: types.contents },
      {
        path: "index.ts",
        contents: emitSchemaModule(schema, options.exportName, nodesModule, header),
      },
    ],
    diagnostics: types.diagnostics,
  };
}
